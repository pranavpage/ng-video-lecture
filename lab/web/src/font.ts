export type Glyph = Uint8Array // row-major bitmask rows, bit 4 = leftmost

function compile(src: Record<string, string>, width: number): Map<string, number[][]> {
  const out = new Map<string, number[][]>()
  for (const [ch, rows] of Object.entries(src)) {
    const pts: number[][] = []
    rows.split(' ').forEach((row, y) => {
      for (let x = 0; x < width; x++) if (row[x] === '#') pts.push([x, y])
    })
    out.set(ch, pts)
  }
  return out
}

export const FONT = compile(G, 5)
export const MICRO_FONT = compile(MICRO, 3)
export const CHAR_W = 6
export const LINE_H = 10

export function glyph(ch: string): number[][] {
  return FONT.get(ch) ?? FONT.get('?')!
}

export function textWidth(s: string, scale = 1): number {
  return s.length * CHAR_W * scale - scale
}

// greedy word wrap to a pixel width; honours explicit newlines
export function wrap(s: string, maxW: number): string[] {
  const maxChars = Math.max(1, Math.floor((maxW + 1) / CHAR_W))
  const out: string[] = []
  for (const para of s.split('\n')) {
    let line = ''
    for (const word of para.split(' ')) {
      if (word.length > maxChars) {
        if (line) { out.push(line); line = '' }
        for (let i = 0; i < word.length; i += maxChars) out.push(word.slice(i, i + maxChars))
        line = out.pop()!
        continue
      }
      const cand = line ? line + ' ' + word : word
      if (cand.length > maxChars) { out.push(line); line = word } else line = cand
    }
    out.push(line)
  }
  return out
}
